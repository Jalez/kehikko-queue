import { resolve } from 'node:path'

import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'
import { beforeDoors, doors, originFor, serves } from 'kehikot-module-protocol/serve'
import { defineConfig, type Plugin } from 'vite'

import { BUILD, MANIFEST, TICKET, answer, isOurs, queue, servingAt, stream } from './doors.ts'
import { QUEUE_DOOR } from './queue/door.ts'
import { ID, PREFERRED_PORT } from './manifest.ts'

/** Once listening, say the port really bound (`serves()` may have moved it): the skills name that origin. */
function origin(): Plugin {
  return {
    name: 'queue-origin',
    apply: 'serve',
    configureServer(server) {
      server.httpServer?.once('listening', () => {
        const address = server.httpServer?.address()
        servingAt(originFor(address && typeof address === 'object' ? address.port : PREFERRED_PORT))
      })
    },
  }
}

/**
 * - `serves()` first: it claims the port from PREFERRED_PORT (or $PORT from a
 *   host) and keeps the registration true. So no `server.port` here.
 * - `doors()` serves everything that is not a source file from this one
 *   process: the manifest, the page at `/app` with the write ticket printed into
 *   it, and `/healthz`, `/mcp`, `/api/*` and each skill's SKILL.md through
 *   `answer` in doors.ts. A module is ONE ORIGIN.
 * - `host: '127.0.0.1'` and `cors: false`: nothing off this machine reaches it,
 *   and no other origin reads the ticket. The manifest declares storage, so the
 *   page is same-origin and needs no CORS header.
 * - No build: the page is generated by `doors()`. `base: './'`, because a host
 *   frames this at whatever address it wrote down.
 */
export default defineConfig({
  base: './',
  plugins: [
    serves({ id: ID, prefer: PREFERRED_PORT }),
    origin(),
    /* The CLI's door and the fence in front of /mcp: before the doors, because they need the headers. */
    beforeDoors(QUEUE_DOOR, { name: 'queue-door', setup: () => void queue() }),
    doors({
      manifest: MANIFEST,
      answer: (method, path, query, body, ticket) => answer(method, path, query, body, ticket),
      stream,
      build: BUILD,
      page: { title: 'Test runs', ticket: TICKET },
      ours: isOurs,
    }),
    react(),
    tailwindcss(),
  ],
  resolve: { alias: { '@': resolve(import.meta.dirname, 'src') } },
  server: { host: '127.0.0.1', cors: false },
  build: { outDir: 'dist', emptyOutDir: true },
})
